import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const solc = require("solc") as {
  compile: (input: string) => string;
};

const sourcePath = resolve("contracts/TokenSafetySimulator.sol");
const source = readFileSync(sourcePath, "utf8");

const input = {
  language: "Solidity",
  sources: {
    "TokenSafetySimulator.sol": { content: source },
  },
  settings: {
    viaIR: true,
    optimizer: { enabled: true, runs: 200 },
    evmVersion: "cancun",
    outputSelection: {
      "*": {
        "*": ["abi", "evm.deployedBytecode.object"],
      },
    },
  },
};

const output = JSON.parse(solc.compile(JSON.stringify(input))) as {
  errors?: Array<{ severity: string; formattedMessage: string }>;
  contracts?: Record<string, Record<string, { abi: unknown; evm: { deployedBytecode: { object: string } } }>>;
};

const errors = (output.errors ?? []).filter((e) => e.severity === "error");
if (errors.length) {
  console.error(errors.map((e) => e.formattedMessage).join("\n"));
  process.exit(1);
}

const contract = output.contracts?.["TokenSafetySimulator.sol"]?.TokenSafetySimulator;
if (!contract?.evm.deployedBytecode.object) {
  console.error("compiler did not return runtime bytecode");
  console.error(JSON.stringify(output.errors ?? [], null, 2));
  process.exit(1);
}

const bytecode = `0x${contract.evm.deployedBytecode.object}`;
const outFile = resolve("src/generated/simulator.ts");
mkdirSync(dirname(outFile), { recursive: true });

const contents = `// Generated by scripts/compile-simulator.ts. Do not edit by hand.
// Source: contracts/TokenSafetySimulator.sol

import type { Hex } from "viem";

export const SIMULATOR_RUNTIME_BYTECODE: Hex = "${bytecode}";
`;

writeFileSync(outFile, contents);
console.log(`wrote ${outFile} (${bytecode.length - 2} hex chars)`);
